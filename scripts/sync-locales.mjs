// Copy locale files dùng chung từ web (source of truth) sang mobile theo allowlist,
// rồi regenerate src/i18n/resources.ts (Metro không dùng được import.meta.glob).
//
// Chạy: node scripts/sync-locales.mjs
// Kiểm tra drift (không ghi): node scripts/sync-locales.mjs --check
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES_ROOT = path.join(projectRoot, "src/i18n/locales");
const WEB_LOCALES_ROOT = path.resolve(projectRoot, "..", "MoveVN-FrontEnd/src/i18n/locales");
const MANIFEST_FILE = path.join(LOCALES_ROOT, ".synced.json");
const RESOURCES_FILE = path.join(projectRoot, "src/i18n/resources.ts");
const LANGUAGES = ["vi", "en"];

// File/thư mục lấy từ web. Thư mục: lấy toàn bộ *.json bên trong.
// Namespace mobile-only (app, favorites, notifications mobile...) không có trong allowlist
// và không bao giờ bị xoá — script chỉ đụng đúng những file đã ghi vào manifest.
const ALLOWLIST = [
  "account.json",
  "accountProfile.json",
  "profile.json",
  "users.json",
  "booking.json",
  "contract.json",
  "disputes.json",
  "faq.json",
  "payments.json",
  "policy.json",
  "promo.json",
  "support.json",
  "tracking.json",
  "violations.json",
  "accountSecurity",
  "accountVerification",
  "accountWallet",
  "auth",
  "common/app.json",
  "common/forms.json",
  "common/notifications.json",
  "common/reviewReply.json",
  "admin/system.json",
  "common/surcharge.json",
  "common/vehicles.json",
  "vehicleDetail",
  "vehicleList",
  "owner",
];

const checkOnly = process.argv.includes("--check");

function walkJson(dir, base = dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkJson(full, base, out);
    else if (entry.name.endsWith(".json")) out.push(path.relative(base, full).replace(/\\/g, "/"));
  }
  return out;
}

function collectAllowlistedFiles(language) {
  const languageRoot = path.join(WEB_LOCALES_ROOT, language);
  const files = [];
  for (const entry of ALLOWLIST) {
    const source = path.join(languageRoot, entry);
    if (!fs.existsSync(source)) {
      console.error(`[sync-locales] Missing in web locales: ${language}/${entry}`);
      process.exit(1);
    }
    if (fs.statSync(source).isDirectory()) {
      for (const file of walkJson(source)) files.push(`${entry}/${file}`);
    } else {
      files.push(entry);
    }
  }
  return [...new Set(files)].sort();
}

function readManifest() {
  try {
    return JSON.parse(fs.readFileSync(MANIFEST_FILE, "utf8"));
  } catch {
    return {};
  }
}

const manifest = readManifest();
const nextManifest = {};
const drift = [];

for (const language of LANGUAGES) {
  const files = collectAllowlistedFiles(language);
  nextManifest[language] = files;

  for (const file of files) {
    const source = path.join(WEB_LOCALES_ROOT, language, file);
    const target = path.join(LOCALES_ROOT, language, file);
    const sourceContent = fs.readFileSync(source, "utf8");
    const targetContent = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;

    if (targetContent === sourceContent) continue;
    if (checkOnly) {
      drift.push(`${language}/${file}`);
      continue;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, sourceContent);
  }

  // Chỉ xoá file do lần sync trước tạo ra và đã bị bỏ khỏi allowlist.
  for (const previous of manifest[language] ?? []) {
    if (files.includes(previous)) continue;
    const stale = path.join(LOCALES_ROOT, language, previous);
    if (!fs.existsSync(stale)) continue;
    if (checkOnly) {
      drift.push(`${language}/${previous} (stale)`);
      continue;
    }
    fs.rmSync(stale);
  }
}

function identifier(language, index) {
  return `${language}_${index}`;
}

function buildResources() {
  const importLines = [];
  const entries = [];
  let index = 0;

  for (const language of LANGUAGES) {
    const languageRoot = path.join(LOCALES_ROOT, language);
    if (!fs.existsSync(languageRoot)) continue;
    const files = walkJson(languageRoot).sort();
    const pairs = [];
    for (const file of files) {
      const name = identifier(language, index++);
      const specifier = `./locales/${language}/${file}`;
      importLines.push(`import ${name} from ${JSON.stringify(specifier)};`);
      pairs.push(`    ${JSON.stringify(file)}: ${name},`);
    }
    entries.push(`  ${language}: {\n${pairs.join("\n")}\n  },`);
  }

  return `// AUTO-GENERATED by scripts/sync-locales.mjs — do not edit by hand.\n// Namespace = thư mục, file = nhóm nội dung (giống web).\n${importLines.join("\n")}\n\nexport const localeModules = {\n${entries.join("\n")}\n};\n`;
}

if (checkOnly) {
  if (drift.length) {
    console.error(`[sync-locales] ${drift.length} file lệch so với web. Chạy lại: node scripts/sync-locales.mjs`);
    for (const file of drift) console.error(`  - ${file}`);
    process.exit(1);
  }
  console.log("[sync-locales] Không có drift so với web.");
  process.exit(0);
}

const nextResources = buildResources();
const currentResources = fs.existsSync(RESOURCES_FILE) ? fs.readFileSync(RESOURCES_FILE, "utf8") : "";
if (nextResources !== currentResources) fs.writeFileSync(RESOURCES_FILE, nextResources);
fs.writeFileSync(MANIFEST_FILE, `${JSON.stringify(nextManifest, null, 2)}\n`);

const synced = LANGUAGES.map((language) => `${language}=${nextManifest[language].length}`).join(", ");
console.log(`[sync-locales] Đã sync (${synced}); resources.ts ${nextResources === currentResources ? "không đổi" : "đã cập nhật"}.`);
